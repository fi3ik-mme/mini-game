function countTypes(bank) {
  let quiz = 0, image = 0, yesno = 0;
  for (const arr of Object.values(bank.categories)) {
    for (const item of arr) {
      if (item.type === "imageQuiz") image++;
      else if (item.type === "yesno") yesno++;
      else quiz++;
    }
  }
  return { quiz, image, yesno, total: quiz + image + yesno };
}

