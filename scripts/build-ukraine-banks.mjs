/** @param {string} text @param {string[]} urls @param {number} correct @param {string} explanation @param {object} [extra] */
function iq(text, urls, correct, explanation, extra = {}) {
  return {
    type: "imageQuiz",
    text,
    imageFit: extra.imageFit || "cover",
    answers: urls.map((image) => ({ image })),
    correct,
    explanation,
    ...extra,
  };
}

function q(text, answers, correct, explanation, extra = {}) {
  return { type: "quiz", text, answers, correct, explanation, ...extra };
}

function yn(text, correct, explanation, extra = {}) {
  return { type: "yesno", text, correct, explanation, ...extra };
}

