const imageMap = new Map();
// Sequential with a small delay — Wikipedia REST API rate-limits parallel
// hits from the same client (returns 429 after ~10 simultaneous requests).
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const HEADERS = {
  "User-Agent": "mini-game-build/1.0 (https://github.com; static site PWA)",
  "Accept": "application/json",
};
async function fetchOne(slug, attempt = 0) {
  const url = "https://uk.wikipedia.org/api/rest_v1/page/summary/" + encodeURI(slug);
  try {
    const res = await fetch(url, { headers: HEADERS });
    if (res.status === 429 && attempt < 3) {
      await sleep(1500 * (attempt + 1));
      return fetchOne(slug, attempt + 1);
    }
    if (!res.ok) return null;
    const data = await res.json();
    // IMPORTANT: use the URL as returned by the API. Wikipedia only pre-renders
    // thumbnails at the widths actually requested by article markup; rewriting
    // `/240px-…` → `/480px-…` produced HTTP 400 for most files. The summary
    // endpoint always returns a usable thumbnail (~320 px wide) which is sized
    // appropriately for the modal via CSS max-width / max-height.
    const src = data?.thumbnail?.source || data?.originalimage?.source;
    return src || null;
  } catch (_) {
    return null;
  }
}
for (const slug of slugs) {
  const src = await fetchOne(slug);
  if (src) imageMap.set(slug, src);
  await sleep(120); // be gentle with the public API
}
console.log("Got Wikipedia images for", imageMap.size, "of", slugs.size, "articles");

// Build the final media block: clickable image (→ Wikipedia) + info-card.
const wikiTextLink = (slug) => {
  const url = "https://uk.wikipedia.org/wiki/" + encodeURI(slug);
  return `<br><a href="${url}" target="_blank" rel="noopener" style="display:inline-block;margin-top:10px;padding:6px 12px;border-radius:8px;background:rgba(56,139,253,0.18);border:1px solid rgba(125,176,255,0.5);color:#cfe1ff;text-decoration:none;font-size:0.9em;font-weight:700">📖 Стаття у Вікіпедії</a>`;
};

const imageBlock = (slug, src) => {
  const url = "https://uk.wikipedia.org/wiki/" + encodeURI(slug);
  return `<a href="${url}" target="_blank" rel="noopener" title="Стаття у Вікіпедії" style="display:block;margin-bottom:10px"><img src="${src}" alt="" loading="lazy" style="display:block;margin:0 auto;max-width:100%;max-height:240px;border-radius:10px;border:1px solid rgba(255,255,255,0.15);background:rgba(255,255,255,0.04);cursor:pointer"/></a>`;
};

let withImage = 0;
let withTextOnly = 0;
for (const q of questions) {
  const slug = matchSlug(q.text);
  if (!slug) continue; // no Wikipedia article — leave info-card alone
  const src = imageMap.get(slug);
  if (src) {
    q.media = imageBlock(slug, src) + q.media;
    withImage++;
  } else {
    q.media = q.media.replace(/<\/div>\s*$/, wikiTextLink(slug) + "</div>");
    withTextOnly++;
  }
}
console.log("Media built —", withImage, "with image, ", withTextOnly, "with text-only Wikipedia link");

